CREATE OR REPLACE TRIGGER trg_chk_salary_range
BEFORE INSERT OR UPDATE OF salary, job_id ON employees
FOR EACH ROW
DECLARE
  v_min_aut jobs.min_salary%TYPE;
  v_max_aut jobs.max_salary%TYPE;
BEGIN
  SELECT min_salary, max_salary
    INTO v_min_aut, v_max_aut
    FROM jobs
   WHERE job_id = :NEW.job_id;

  IF :NEW.salary < v_min_aut OR :NEW.salary > v_max_aut THEN
    RAISE_APPLICATION_ERROR(-20010,
      'Salario fuera de rango para el puesto ('||:NEW.job_id||')');
  END IF;
END;
/

CREATE OR REPLACE TRIGGER trg_mark_inasistencia
BEFORE INSERT OR UPDATE OF hora_inicio_real, fecha_real ON asistencia_empleado
FOR EACH ROW
DECLARE
  v_turno_asignado empleado_horario.turno%TYPE;
  v_plan_ini       DATE;
  v_plan_fin       DATE;
  v_inicio_real    DATE;
  v_dia_sem        NUMBER;
BEGIN
  v_dia_sem := TO_NUMBER(TO_CHAR(:NEW.fecha_real,'D'));

  SELECT eh.turno
    INTO v_turno_asignado
    FROM empleado_horario eh
   WHERE eh.employee_id = :NEW.employee_id
     AND eh.dia_semana  = v_dia_sem;

  SELECT h.hora_inicio, h.hora_termino
    INTO v_plan_ini, v_plan_fin
    FROM horario h
   WHERE h.dia_semana = v_dia_sem
     AND h.turno      = v_turno_asignado;

  v_inicio_real := :NEW.hora_inicio_real;

  IF v_inicio_real < (:NEW.fecha_real + (v_plan_ini - TRUNC(v_plan_ini)) - (30/1440))
     OR v_inicio_real > (:NEW.fecha_real + (v_plan_ini - TRUNC(v_plan_ini)) + (30/1440)) THEN
    :NEW.inasistencia := 'S';
    :NEW.hora_termino_real := :NEW.hora_inicio_real;
  ELSE
    :NEW.inasistencia := 'N';
  END IF;
EXCEPTION
  WHEN NO_DATA_FOUND THEN
    :NEW.inasistencia := 'S';
    :NEW.hora_termino_real := :NEW.hora_inicio_real;
END;
/
