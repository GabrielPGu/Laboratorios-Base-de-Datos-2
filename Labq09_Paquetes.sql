CREATE OR REPLACE PACKAGE BODY hr_pack AS

  PROCEDURE alta_empleado(p_id_emp NUMBER, p_apellido VARCHAR2, p_nombre VARCHAR2,
                          p_correo VARCHAR2, p_f_ingreso DATE, p_puesto VARCHAR2,
                          p_sueldo NUMBER, p_depto NUMBER) IS
  BEGIN
    INSERT INTO employees(employee_id, last_name, first_name, email, hire_date, job_id, salary, department_id)
    VALUES (p_id_emp, p_apellido, p_nombre, p_correo, p_f_ingreso, p_puesto, p_sueldo, p_depto);
  END alta_empleado;

  PROCEDURE leer_empleado(p_id_emp NUMBER, p_cursor OUT SYS_REFCURSOR) IS
  BEGIN
    OPEN p_cursor FOR
      SELECT *
        FROM employees
       WHERE employee_id = p_id_emp;
  END leer_empleado;

  PROCEDURE actualizar_empleado(p_id_emp NUMBER, p_apellido VARCHAR2, p_nombre VARCHAR2,
                                p_correo VARCHAR2, p_puesto VARCHAR2,
                                p_sueldo NUMBER, p_depto NUMBER) IS
  BEGIN
    UPDATE employees
       SET last_name     = COALESCE(p_apellido, last_name),
           first_name    = COALESCE(p_nombre, first_name),
           email         = COALESCE(p_correo, email),
           job_id        = COALESCE(p_puesto, job_id),
           salary        = COALESCE(p_sueldo, salary),
           department_id = COALESCE(p_depto, department_id)
     WHERE employee_id   = p_id_emp;
  END actualizar_empleado;

  PROCEDURE eliminar_empleado(p_id_emp NUMBER) IS
  BEGIN
    DELETE FROM employees WHERE employee_id = p_id_emp;
  END eliminar_empleado;

  PROCEDURE rotacion_puestos_top4(p_cursor OUT SYS_REFCURSOR) IS
  BEGIN
    OPEN p_cursor FOR
      SELECT e.employee_id,
             e.last_name  AS apellido,
             e.first_name AS nombre,
             e.job_id     AS puesto_actual,
             (SELECT j.job_title FROM jobs j WHERE j.job_id = e.job_id) AS puesto_actual_desc,
             NVL((SELECT COUNT(*) FROM job_history jh WHERE jh.employee_id = e.employee_id),0) AS cambios_puesto
      FROM employees e
      ORDER BY cambios_puesto DESC, e.employee_id
      FETCH FIRST 4 ROWS ONLY;
  END rotacion_puestos_top4;

  FUNCTION promedio_contratos_mensual(p_cursor OUT SYS_REFCURSOR) RETURN NUMBER IS
    v_meses_dist INT;
  BEGIN
    OPEN p_cursor FOR
      SELECT TO_CHAR(mes_ref,'Month','NLS_DATE_LANGUAGE=English') AS mes,
             ROUND(AVG(cantidad),2) AS promedio_contrataciones
      FROM (
        SELECT TRUNC(hire_date,'MM') mes_ref, COUNT(*) cantidad
          FROM employees
         GROUP BY TRUNC(hire_date,'MM')
      )
      GROUP BY TO_CHAR(mes_ref,'Month','NLS_DATE_LANGUAGE=English'), EXTRACT(MONTH FROM mes_ref)
      ORDER BY EXTRACT(MONTH FROM mes_ref);
    SELECT COUNT(DISTINCT EXTRACT(MONTH FROM hire_date))
      INTO v_meses_dist
      FROM employees;
    RETURN v_meses_dist;
  END promedio_contratos_mensual;

  PROCEDURE reporte_regional(p_cursor OUT SYS_REFCURSOR) IS
  BEGIN
    OPEN p_cursor FOR
      SELECT r.region_name AS region,
             SUM(e.salary) AS total_salarios,
             COUNT(e.employee_id) AS total_empleados,
             MIN(e.hire_date) AS primer_ingreso
        FROM regions r
        JOIN countries  c ON c.region_id   = r.region_id
        JOIN locations  l ON l.country_id  = c.country_id
        JOIN departments d ON d.location_id = l.location_id
        JOIN employees  e ON e.department_id = d.department_id
       GROUP BY r.region_name
       ORDER BY r.region_name;
  END reporte_regional;

  FUNCTION antiguedad_personal(p_cursor OUT SYS_REFCURSOR) RETURN NUMBER IS
    v_total_meses NUMBER;
  BEGIN
    OPEN p_cursor FOR
      SELECT e.employee_id,
             e.first_name,
             e.last_name,
             MONTHS_BETWEEN(TRUNC(SYSDATE), TRUNC(e.hire_date)) AS meses_servicio,
             FLOOR(MONTHS_BETWEEN(TRUNC(SYSDATE), TRUNC(e.hire_date))/12) AS anios,
             FLOOR(MONTHS_BETWEEN(TRUNC(SYSDATE), TRUNC(e.hire_date))/12) AS meses_vacaciones
        FROM employees e;

    SELECT SUM(MONTHS_BETWEEN(TRUNC(SYSDATE), TRUNC(hire_date)))
      INTO v_total_meses
      FROM employees;

    RETURN v_total_meses;
  END antiguedad_personal;

  FUNCTION dif_horas(p_inicio DATE, p_fin DATE) RETURN NUMBER IS
  BEGIN
    RETURN ROUND((p_fin - p_inicio) * 24, 2);
  END dif_horas;

  FUNCTION horas_laboradas(p_id_empleado NUMBER, p_mes NUMBER, p_anio NUMBER) RETURN NUMBER IS
    v_horas NUMBER := 0;
  BEGIN
    SELECT NVL(SUM(dif_horas(hora_inicio_real, hora_termino_real)),0)
      INTO v_horas
      FROM asistencia_empleado a
     WHERE a.employee_id = p_id_empleado
       AND EXTRACT(MONTH FROM a.fecha_real) = p_mes
       AND EXTRACT(YEAR  FROM a.fecha_real) = p_anio
       AND a.inasistencia = 'N';
    RETURN v_horas;
  END horas_laboradas;

  FUNCTION horas_ausentes(p_id_empleado NUMBER, p_mes NUMBER, p_anio NUMBER) RETURN NUMBER IS
    v_prog NUMBER := 0;
    v_real NUMBER := 0;
  BEGIN
    SELECT NVL(SUM(
             dif_horas(
               TO_DATE('2000-01-01','YYYY-MM-DD') + (SELECT h.hora_inicio - TRUNC(h.hora_inicio)
                                                       FROM horario h
                                                      WHERE h.dia_semana = TO_NUMBER(TO_CHAR(d,'D'))),
               TO_DATE('2000-01-01','YYYY-MM-DD') + (SELECT h.hora_termino - TRUNC(h.hora_termino)
                                                       FROM horario h
                                                      WHERE h.dia_semana = TO_NUMBER(TO_CHAR(d,'D')))
           )),0)
      INTO v_prog
      FROM (
        SELECT (TRUNC(ADD_MONTHS(DATE '2000-01-01', (p_anio-2000)*12 + (p_mes-1))) + (LEVEL-1)) d
          FROM dual
        CONNECT BY LEVEL <= EXTRACT(DAY FROM LAST_DAY(TO_DATE(p_anio||LPAD(p_mes,2,'0'),'YYYYMM')))
      ) cal
      WHERE EXISTS (
        SELECT 1
          FROM empleado_horario eh
         WHERE eh.employee_id = p_id_empleado
           AND eh.dia_semana  = TO_NUMBER(TO_CHAR(d,'D'))
      );

    v_real := horas_laboradas(p_id_empleado, p_mes, p_anio);
    RETURN GREATEST(v_prog - v_real, 0);
  END horas_ausentes;

  PROCEDURE nomina_proporcional(p_mes NUMBER, p_anio NUMBER, p_cursor OUT SYS_REFCURSOR) IS
  BEGIN
    OPEN p_cursor FOR
      WITH prog AS (
        SELECT e.employee_id,
               hr_pack.horas_ausentes(e.employee_id, p_mes, p_anio)  AS hrs_falta,
               hr_pack.horas_laboradas(e.employee_id, p_mes, p_anio) AS hrs_trab
          FROM employees e
      ), base AS (
        SELECT employee_id, hrs_trab, hrs_falta, (hrs_trab + hrs_falta) AS hrs_prog
          FROM prog
      )
      SELECT e.first_name, e.last_name, e.salary,
             CASE 
               WHEN b.hrs_prog > 0 THEN ROUND(e.salary * (b.hrs_trab / b.hrs_prog), 2)
               ELSE 0
             END AS sueldo_calculado
        FROM base b
        JOIN employees e ON e.employee_id = b.employee_id
       ORDER BY sueldo_calculado DESC NULLS LAST;
  END nomina_proporcional;

  FUNCTION horas_formacion_empleado(p_id_empleado NUMBER) RETURN NUMBER IS
    v_total NUMBER;
  BEGIN
    SELECT NVL(SUM(c.horas),0)
      INTO v_total
      FROM empleado_capacitacion ec
      JOIN capacitacion c ON c.capacitacion_id = ec.capacitacion_id
     WHERE ec.employee_id = p_id_empleado;
    RETURN v_total;
  END horas_formacion_empleado;

  PROCEDURE listado_formaciones(p_cursor OUT SYS_REFCURSOR) IS
  BEGIN
    OPEN p_cursor FOR
      SELECT c.capacitacion_id,
             c.nombre AS capacitacion,
             e.employee_id,
             e.first_name,
             e.last_name,
             c.horas
        FROM capacitacion c
        LEFT JOIN empleado_capacitacion ec ON ec.capacitacion_id = c.capacitacion_id
        LEFT JOIN employees e ON e.employee_id = ec.employee_id
       ORDER BY c.horas DESC, c.nombre, e.last_name, e.first_name;
  END listado_formaciones;

END hr_pack;
