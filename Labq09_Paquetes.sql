CREATE OR REPLACE TRIGGER trg_chk_asistencia
BEFORE INSERT OR UPDATE ON asistencia_empleado
FOR EACH ROW
DECLARE
  v_turno_asignado empleado_horario.turno%TYPE;
  v_plan_ini       DATE;
  v_plan_fin       DATE;
  v_dia_sem        NUMBER;
BEGIN
  v_dia_sem := TO_NUMBER(TO_CHAR(:NEW.fecha_real, 'D'));
  IF :NEW.dia_semana <> v_dia_sem THEN
    RAISE_APPLICATION_ERROR(-20001, 'Día de semana no coincide con la fecha.');
  END IF;

  SELECT eh.turno
    INTO v_turno_asignado
    FROM empleado_horario eh
   WHERE eh.employee_id = :NEW.employee_id
     AND eh.dia_semana  = :NEW.dia_semana;

  SELECT h.hora_inicio, h.hora_termino
    INTO v_plan_ini, v_plan_fin
    FROM horario h
   WHERE h.dia_semana = :NEW.dia_semana
     AND h.turno      = v_turno_asignado;

  IF :NEW.hora_inicio_real < (:NEW.fecha_real + (v_plan_ini - TRUNC(v_plan_ini)) - (30/1440))
     OR :NEW.hora_termino_real > (:NEW.fecha_real + (v_plan_fin - TRUNC(v_plan_fin)) + (30/1440)) THEN
    RAISE_APPLICATION_ERROR(-20002, 'Horas reales fuera de rango razonable respecto al plan.');
  END IF;
EXCEPTION
  WHEN NO_DATA_FOUND THEN
    RAISE_APPLICATION_ERROR(-20003, 'No existe turno programado para el empleado en ese día.');
END;
